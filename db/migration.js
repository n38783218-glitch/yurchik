// Импортируем класс для работы с SQLite базой данных
import SqliteLinker from './sqlite.js';

/**
 * Функция для применения миграции.
 * Здесь описываем изменения, которые нужно внести в базу:
 * создать таблицы, добавить поля, индексы и так далее.
 */
async function up() {}

/**
 * Функция для отката миграции.
 * Здесь описываем, как отменить изменения из up():
 * удалить таблицы, поля, индексы и так далее.
 */
async function down() {}

/**
 * Выполняет SQL-запрос к базе данных.
 * @param {string} sql - SQL-запрос, который нужно выполнить
 * @returns {Promise} - результат выполнения запроса
 */
async function exec(sql) {
  // Проверяем, что нам передали именно строку и что она не пустая.
  // Если это не так — сразу выбрасываем ошибку, чтобы не открывать базу зря.
  if (typeof sql !== 'string' || sql.trim().length === 0) {
    throw new Error('SQL must be a non-empty string');
  }

  // Создаём объект для подключения к файлу базы данных.
  const linker = new SqliteLinker('./database.db');

  try {
    // Открываем соединение с базой.
    await linker.connect();

    // Выполняем переданный SQL-запрос и возвращаем результат.
    return await linker.run(sql);
  } catch (err) {
    // Если что-то пошло не так — выводим ошибку в консоль,
    // чтобы было понятно, что именно сломалось.
    console.error('Migration error:', err);

    // Пробрасываем ошибку наверх, но с понятным сообщением.
    // cause сохраняет исходную ошибку, чтобы не потерять детали.
    throw new Error('Migration failed. Check the SQL and try again.', {
      cause: err,
    });
  } finally {
    // Этот блок выполняется всегда — и при успехе, и при ошибке.
    // Закрываем соединение, чтобы освободить ресурсы.
    // Проверка if (linker) нужна на случай, если соединение не успело открыться.
    if (linker) {
      await linker.close();
    }
  }
}

// Отдаём функции up и down наружу — их будет вызывать система миграций.
// exec наружу не отдаём, это внутренняя помощница.
export { up, down };
